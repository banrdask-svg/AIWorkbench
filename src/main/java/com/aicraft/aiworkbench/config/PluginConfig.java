package com.aicraft.aiworkbench.config;

import org.bukkit.configuration.file.FileConfiguration;

public record PluginConfig(
        boolean aiEnabled,
        String baseUrl,
        String apiKey,
        String model,
        String reasoningEffort,
        int timeoutSeconds,
        boolean retryOnInvalidJson,
        int promptMaxLength,
        int generationsPerMinute,
        int maxConcurrentGenerations,
        int maxAiResponseChars,
        int minCooldownSeconds,
        int maxCooldownSeconds,
        double maxAbilityPower,
        int maxDurationSeconds,
        double maxRadius,
        int maxRecipeOutput,
        boolean resourcePackEnabled,
        String resourcePackDownloadUrl,
        int maxTextureBytes,
        int textureSize,
        int maxTexturesPerItem,
        int maxAnimationFrames,
        int maxModelCubes,
        String packVersionFile,
        boolean geminiEnabled,
        String geminiApiKey,
        String geminiBaseUrl,
        String geminiModel,
        int geminiTimeoutSeconds,
        String geminiImageSize,
        boolean debug
) {
    public static PluginConfig from(FileConfiguration config) {
        return new PluginConfig(
                config.getBoolean("ai.enabled", true),
                config.getString("ai.base-url", "https://api.deepseek.com/chat/completions"),
                config.getString("ai.api-key", ""),
                config.getString("ai.model", "deepseek-flash"),
                config.getString("ai.reasoning-effort", "medium"),
                config.getInt("ai.timeout-seconds", 60),
                config.getBoolean("ai.retry-on-invalid-json", true),
                config.getInt("limits.prompt-max-length", 500),
                config.getInt("limits.generations-per-minute", 3),
                config.getInt("limits.max-concurrent-generations", 5),
                config.getInt("limits.max-ai-response-chars", 24000),
                config.getInt("limits.min-cooldown-seconds", 3),
                config.getInt("limits.max-cooldown-seconds", 60),
                config.getDouble("limits.max-ability-power", 8.0),
                config.getInt("limits.max-duration-seconds", 20),
                config.getDouble("limits.max-radius", 6.0),
                config.getInt("limits.max-recipe-output", 1),
                config.getBoolean("resource-pack.enabled", true),
                config.getString("resource-pack.download-url", ""),
                config.getInt("resource-pack.max-texture-bytes", 1048576),
                config.getInt("resource-pack.texture-size", 16),
                config.getInt("visual.max-textures-per-item", 8),
                config.getInt("visual.max-animation-frames", 16),
                config.getInt("visual.max-model-cubes", 24),
                config.getString("visual.pack-version-file", "pack-version.txt"),
                config.getBoolean("gemini.enabled", false),
                config.getString("gemini.api-key", ""),
                config.getString("gemini.base-url", "https://generativelanguage.googleapis.com/v1beta/interactions"),
                config.getString("gemini.model", "gemini-3.1-flash-image"),
                config.getInt("gemini.timeout-seconds", 90),
                config.getString("gemini.image-size", "1K"),
                config.getBoolean("debug", false)
        );
    }
}
